/// The English name for a legacy Spanish one, or the name itself when it is not an alias.
pub fn canonical_param_name(name: &str) -> &str {
    PARAM_NAME_ALIASES.iter().find(|(old, _)| *old == name).map_or(name, |(_, new)| *new)
}

/// Every key a parameter `name` may be stored under: the English name first, then the
/// Spanish names that alias it. Callers look a config key up through this, so a
/// Spanish-keyed graph still resolves.
pub fn alias_keys(name: &str) -> impl Iterator<Item = &str> {
    let name = canonical_param_name(name);
    std::iter::once(name).chain(PARAM_NAME_ALIASES.iter().filter(move |(_, new)| *new == name).map(|(old, _)| *old))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spanish_names_resolve_to_their_english_names() {
        assert_eq!(canonical_param_name("subida"), "rise");
        assert_eq!(canonical_param_name("fondo"), "background");
        assert_eq!(canonical_param_name("rise"), "rise");
        assert_eq!(canonical_param_name("unknown_name"), "unknown_name");
    }

    #[test]
    fn alias_keys_offer_the_english_name_then_its_legacy_names() {
        let keys: Vec<&str> = alias_keys("rise").collect();
        assert_eq!(keys[0], "rise");
        assert!(keys.contains(&"subida"));
        // A Spanish name in, the same English key list out.
        assert_eq!(alias_keys("subida").collect::<Vec<_>>(), keys);
    }

    #[test]
    fn the_table_maps_each_spanish_name_once() {
        let mut seen = std::collections::HashSet::new();
        for (old, _) in PARAM_NAME_ALIASES {
            assert!(seen.insert(*old), "duplicate alias {old}");
        }
    }
}
